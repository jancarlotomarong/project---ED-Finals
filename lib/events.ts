import { supabase } from './supabase';
import { cleanText } from './validation';

export type EventStatus = 'open' | 'closed';

export type CloudEvent = {
  id: string;
  event_code: string;
  title: string;
  description: string | null;
  venue: string | null;
  start_time: string | null;
  end_time: string | null;
  status: EventStatus;
  created_by: string | null;
  created_at: string;
  updated_at: string;
};

export type EventWithCount = CloudEvent & { attendeeCount: number };

/** Display state: combines the stored status with the clock. */
export type EventState = 'closed' | 'upcoming' | 'ongoing' | 'ended';

export function getEventState(ev: Pick<CloudEvent, 'status' | 'start_time' | 'end_time'>): EventState {
  if (ev.status === 'closed') return 'closed';
  const now = Date.now();
  if (ev.start_time && now < new Date(ev.start_time).getTime()) return 'upcoming';
  if (ev.end_time && now > new Date(ev.end_time).getTime()) return 'ended';
  return 'ongoing';
}

export type EventFields = {
  title: string;
  description: string;
  venue: string;
  start: Date;
  end: Date;
};

function toRow(fields: EventFields) {
  return {
    title: cleanText(fields.title, 120),
    description: fields.description.trim() ? fields.description.trim().slice(0, 500) : null,
    venue: cleanText(fields.venue, 120),
    start_time: fields.start.toISOString(),
    end_time: fields.end.toISOString(),
  };
}

function friendly(error: { code?: string; message: string }) {
  if (error.code === '42501') return 'You do not have permission to do that.';
  if (error.code === '23505') return 'An event with that code already exists.';
  return error.message;
}

const NO_PERMISSION = 'You do not have permission to change this event.';

export async function createEvent(
  fields: EventFields,
  userId: string
): Promise<{ event: CloudEvent | null; error: string | null }> {
  // event_code is generated by the database (default value).
  const { data, error } = await supabase
    .from('events')
    .insert({ ...toRow(fields), created_by: userId })
    .select('*')
    .single();

  if (error || !data) {
    return { event: null, error: error ? friendly(error) : 'Could not create the event.' };
  }
  return { event: data as CloudEvent, error: null };
}

export async function updateEvent(
  id: string,
  fields: EventFields
): Promise<{ error: string | null }> {
  const { data, error } = await supabase
    .from('events')
    .update(toRow(fields))
    .eq('id', id)
    .select('id');
  if (error) return { error: friendly(error) };
  if (!data || data.length === 0) return { error: NO_PERMISSION };
  return { error: null };
}

export async function setEventStatus(
  id: string,
  status: EventStatus
): Promise<{ error: string | null }> {
  const { data, error } = await supabase
    .from('events')
    .update({ status })
    .eq('id', id)
    .select('id');
  if (error) return { error: friendly(error) };
  if (!data || data.length === 0) return { error: NO_PERMISSION };
  return { error: null };
}

export async function deleteEvent(id: string): Promise<{ error: string | null }> {
  const { data, error } = await supabase.from('events').delete().eq('id', id).select('id');
  if (error) return { error: friendly(error) };
  if (!data || data.length === 0) return { error: 'Only administrators can delete events.' };
  return { error: null };
}

export async function getEventById(
  id: string
): Promise<{ event: CloudEvent | null; error: string | null }> {
  const { data, error } = await supabase.from('events').select('*').eq('id', id).maybeSingle();
  if (error) return { event: null, error: error.message };
  return { event: (data as CloudEvent | null) ?? null, error: null };
}

/** All events (students use this to browse available events). */
export async function listEvents(): Promise<{ data: CloudEvent[]; error: string | null }> {
  const { data, error } = await supabase
    .from('events')
    .select('*')
    .order('start_time', { ascending: false })
    .limit(200);
  if (error) return { data: [], error: error.message };
  return { data: (data ?? []) as CloudEvent[], error: null };
}

/** Teacher: pass their id (own events). Admin: omit (all events). */
export async function listEventsWithCounts(
  createdBy?: string
): Promise<{ data: EventWithCount[]; error: string | null }> {
  let query = supabase
    .from('events')
    .select('*, attendance(count)')
    .order('start_time', { ascending: false })
    .limit(200);
  if (createdBy) query = query.eq('created_by', createdBy);

  const { data, error } = await query;
  if (error) return { data: [], error: error.message };

  const rows = ((data ?? []) as any[]).map((row) => {
    const { attendance, ...event } = row;
    return { ...(event as CloudEvent), attendeeCount: attendance?.[0]?.count ?? 0 };
  });
  return { data: rows, error: null };
}
